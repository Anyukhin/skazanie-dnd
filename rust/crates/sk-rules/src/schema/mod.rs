//! Версия схемы состояния кампании и миграции снимков (урок 4).
//!
//! Снимок журнала (`sk-store`) хранит `state_schema_version` — форму, в
//! которой лежит его состояние:
//!
//! - **0** — версии нет: снимки прежних сборок Rust и файлы JS. Форма —
//!   какая получилась у записавшего; состояние нормализуется при загрузке;
//! - **1** — итог нормализации этого движка в текущем режиме удержания.
//!
//! Загрузка снимка известной версии — проверка формы ([`shape`]) и состояние
//! как есть, без нормализации; снимок старой версии проходит цепочку
//! [`migrations`] (v0→v1 — нынешняя нормализация). Миграция идёт в памяти:
//! на диске снимок остаётся прежним, новая версия ляжет со следующим
//! обычным снимком. Схема событий от этого не меняется.
//!
//! **Правка нормализации, меняющая итог для уже нормализованного состояния,
//! поднимает [`STATE_SCHEMA_VERSION`] и добавляет шаг миграции**: иначе
//! снимки прежней формы загрузились бы без неё.

pub mod migrations;
pub mod shape;

/// Текущая версия схемы состояния в снимке.
pub const STATE_SCHEMA_VERSION: i64 = 1;
