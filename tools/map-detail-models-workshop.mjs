/** Низкая куча кусков угля с лопатой. */
function coalPile(m) {
  // Куча угля: неровный купол и россыпь кусков; лопата воткнута в склон
  // и лежит полого, чтобы не выйти за низкий габарит предмета.
  m.lumpy('угольная-куча:купол', new THREE.SphereGeometry(0.5, 36, 12, 0, Math.PI * 2, 0, Math.PI / 2), [-0.05, 0, -0.02], C.coal,
    { size: [0.98, 0.30, 0.92], amount: 0.035, frequency: 6, seed: 3 })
  const next = random(19)
  for (let index = 0; index < 34; index += 1) {
    const angle = next() * Math.PI * 2, ring = next()
    const x = -0.05 + Math.cos(angle) * 0.50 * (0.25 + ring * 0.85), z = -0.02 + Math.sin(angle) * 0.47 * (0.25 + ring * 0.85)
    const dome = 0.15 * Math.sqrt(Math.max(0, 1 - ((x + 0.05) / 0.5) ** 2 - ((z + 0.02) / 0.47) ** 2))
    const s = 0.07 + next() * 0.07
    m.lumpy('угольная-куча:кусок', new THREE.DodecahedronGeometry(0.5, 0), [x, dome * 1.9 + s * 0.2, z], index % 4 ? C.coal : C.stoneDark,
      { size: [s, s * 0.75, s * 0.9], amount: s * 0.15, frequency: 12, seed: 50 + index, rotation: [next() * 3, next() * 3, 0] })
  }
  // Лопата: штык вошёл в уголь, черенок поднимается к D-образной ручке.
  m.box('угольная-куча:штык-лопаты-metal', [0.26, 0.018, 0.30], [0.22, 0.17, 0.12], C.iron, [0.10, 0.6, 0.42])
  m.beam('угольная-куча:тулейка-metal', [0.30, 0.22, 0.20], [0.37, 0.25, 0.26], 0.03, C.iron)
  m.beam('угольная-куча:черенок', [0.33, 0.235, 0.23], [0.72, 0.36, 0.55], 0.024, C.woodLight)
  m.torus('угольная-куча:ручка', 0.06, 0.016, [0.76, 0.375, 0.58], C.woodLight, [0.3, 0.88, 0])
}

