/** Вертикальное колесо с ободом, лопастями и выступающей осью. */
function waterWheel(m) {
  const centerY = 2
  m.cylinder('колесо:ступица', 0.25, 0.25, 0.34, [0, centerY, 0], C.iron, 12, [0, 0, Math.PI / 2])
  m.cylinder('колесо:диск', 1.58, 1.58, 0.12, [0, centerY, 0], C.wood, 12, [0, 0, Math.PI / 2])
  m.torus('колесо:обод', 1.68, 0.1, [0, centerY, 0], C.woodLight, [0, Math.PI / 2, 0])
  for (let index = 0; index < 8; index += 1) {
    const angle = (index * Math.PI) / 4
    const y = centerY + Math.sin(angle) * 1.25
    const z = Math.cos(angle) * 1.25
    m.box('колесо:лопасть', [0.18, 0.62, 0.12], [0, y, z], C.woodLight, [angle, 0, 0])
  }
  m.beam('колесо:ось', [-0.54, centerY, 0], [0.54, centerY, 0], 0.09, C.iron)
}

