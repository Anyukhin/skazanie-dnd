/** Добавляет четыре простые ножки под предмет мебели. */
function legs(m, prefix, width, depth, y, height, color, inset = 0.12) {
  const x = Math.max(0.04, width / 2 - inset)
  const z = Math.max(0.04, depth / 2 - inset)
  for (const [px, pz] of [[-x, -z], [x, -z], [-x, z], [x, z]]) {
    m.box(`${prefix}:ножка`, [0.1, height, 0.1], [px, height / 2, pz], color)
  }
}

