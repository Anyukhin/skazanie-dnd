  // Два обода с распорками, сквозные лопасти и спицы; ось выходит в одну сторону.
  const centerY = 2.0, rim = 1.62
  m.cylinder('колесо:ступица-metal', 0.24, 0.24, 0.78, [0, centerY, 0], C.iron, 24, [0, 0, Math.PI / 2])
  m.beam('колесо:ось-metal', [-0.52, centerY, 0], [0.62, centerY, 0], 0.075, C.iron)
