const clean = (value) => String(value ?? '').trim()

/**
 * Пусты ли творческие поля мастера. Проверяется по группам: жанр, место и
 * завязка независимы, и заполнить можно любую из них.
 */
function emptiness(world = {}) {
  const genre = !clean(world.genre) && !clean(world.preset)
  const place = !clean(world.startingLocation)
  const story = !clean(world.premise) && !clean(world.openingSituation) && !clean(world.themes)
  return { genre, place, story, any: genre || place || story }
}

/**
 * Один элемент пула серверным броском. `DiceService` — единственный источник
 * случайности в проекте, и заводить здесь второй было бы ровно тем дублем,
 * который карта кода запрещает.
 */
function pick(pool, diceService, purpose) {
  if (!diceService) return pool[0]
  const roll = diceService.roll(`1d${pool.length}`, purpose, 'campaign-bootstrap', 'gm_only')
  const index = Math.max(1, Math.min(pool.length, Number(roll.total) || 1)) - 1
  return pool[index]
}

/**
 * Зерно для этой кампании. Возвращает только то, что действительно нужно: если
 * игрок заполнил мастер целиком, `applied` будет `false`, и в задание модели
 * ничего не подмешается.
 *
 * @param {{ world?: Record<string, any>, diceService?: any }} input
 */
export function drawCampaignInspiration({ world = {}, diceService = null } = {}) {
  const empty = emptiness(world)
  if (!empty.any) {
    return { policy_id: CAMPAIGN_INSPIRATION_POLICY_ID, applied: false, genreLean: null, region: null, hook: null, detail: null }
  }
  return {
    policy_id: CAMPAIGN_INSPIRATION_POLICY_ID,
    applied: true,
    genreLean: empty.genre ? pick(INSPIRATION_GENRE_LEANS, diceService, 'campaign_inspiration:genre') : null,
    region: empty.place ? pick(INSPIRATION_REGIONS, diceService, 'campaign_inspiration:region') : null,
    hook: empty.story ? pick(INSPIRATION_HOOKS, diceService, 'campaign_inspiration:hook') : null,
    // Деталь — единственное, что подмешивается при любом пробеле: она не
    // спорит с заполненными полями, а достраивает их конкретностью.
    detail: pick(INSPIRATION_DETAILS, diceService, 'campaign_inspiration:detail'),
  }
}

/**
 * Зерно в виде, пригодном для задания модели. `null`, когда подмешивать нечего:
 * пустой блок в промпте читался бы как «ориентиров нет вовсе».
 *
 * @param {ReturnType<typeof drawCampaignInspiration>} inspiration
 */
export function inspirationPromptSeed(inspiration) {
  if (!inspiration?.applied) return null
  return {
    note: 'Ориентиры только для полей, которые владелец оставил пустыми. Всё, что владелец указал явно, важнее этих ориентиров и не переписывается.',
    ...(inspiration.genreLean ? { genre_lean: inspiration.genreLean } : {}),
    ...(inspiration.region ? { region: inspiration.region.label } : {}),
    ...(inspiration.hook ? { hook_nature: inspiration.hook } : {}),
    ...(inspiration.detail ? { world_detail: inspiration.detail } : {}),
  }
}
