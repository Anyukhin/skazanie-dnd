function safeRound(value) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) return null
  const id = text(value.id, 140)
  const heroId = text(value.hero_id, 120)
  const npcId = text(value.npc_id, 120)
  if (!id || !heroId || !npcId) return null
  const stakeCp = TAVERN_STAKES_CP.includes(integer(value.stake_cp, 0)) ? integer(value.stake_cp, 0) : TAVERN_STAKES_CP[0]
  const npcTotal = clamp(value.npc_total, 1, 20)
  return {
    id,
    hero_id: heroId,
    npc_id: npcId,
    npc_name: text(value.npc_name, 160),
    // Ставка — это **уже уплаченные** деньги, а не намерение: при открытии
    // раунда она ушла из кошелька в банк стола. Второго поля под эскроу здесь
    // нет намеренно: эскроу равен ставке всегда, и два числа с одним смыслом
    // однажды разошлись бы.
    stake_cp: stakeCp,
    npc_total: npcTotal,
    // Число, которое герою надо перебить. Хранится рядом с броском, потому что
    // именно оно уезжает в карточку ручного броска: считать его дважды —
    // значит однажды посчитать по-разному.
    target: npcTotal + 1,
    opened_at_minutes: Math.max(0, integer(value.opened_at_minutes, 0)),
  }
}

/**
 * Запись посетителя: его кружки, его скандалы, его запрет входа и **его**
 * раунд. Раунд лежит здесь, а не в заведении, потому что стол в этой игре —
 * стол на пятерых: общий слот запирал бы кости всему залу, пока один игрок не
 * ответит, и запирал бы навсегда, если ответить он уже не может.
 */
function safePatron(value) {
  return {
    drinks: clamp(value?.drinks, 0, 99),
    scandals: clamp(value?.scandals, 0, 99),
    ejected: value?.ejected === true,
    round: safeRound(value?.round),
  }
}

/**
 * Чего стоит запись посетителя. Нужна ровно там же, где минута последней игры у
 * касс, и ровно затем же: лишнее вытесняется по весу, а не отбрасывается
 * срезом.
 *
 * Вес считается от того, чем пропажа записи обернётся **подарком**: запрет
 * входа дороже скандала (снимает выставленного за дверь как не бывало), скандал
 * дороже открытого раунда, раунд дороже выпитого. Ноль означает буквально
 * «этой записи всё равно что нет»: пустого посетителя выбросить не стоит
 * ничего, потому что `safePatron` вернёт ровно такого же.
 */
function patronWeight(patron) {
  return (patron.ejected ? 8 : 0) + (patron.scandals ? 4 : 0) + (patron.round ? 2 : 0) + (patron.drinks ? 1 : 0)
}

export function normalizeTavernState(input = {}) {
  const source = input && typeof input === 'object' && !Array.isArray(input) ? input : {}
  const patrons = {}
  for (const [heroId, patron] of Object.entries(source.patrons ?? {})) {
    const id = text(heroId, 120)
    if (id) patrons[id] = safePatron(patron)
  }
  // Снимок первой редакции держал раунд одним полем на всё заведение. Журнал
  // такого не знает — события всегда несли `hero_id`, — но снимок мог, и
  // переезд стоит трёх строк.
  //
  // Переезд идёт **до** предела, а не после: иначе легаси-раунд добавлял бы
  // тринадцатую запись поверх двенадцати уже отобранных.
  const legacy = safeRound(source.round)
  if (legacy && !patrons[legacy.hero_id]?.round) {
    patrons[legacy.hero_id] = { ...safePatron(patrons[legacy.hero_id]), round: legacy }
  }
  // Ключ сортировки двойной — вес, а при совпадении порядок в объекте: двух
  // разных ответов на «кого забыть» быть не должно, иначе replay разойдётся со
  // снимком.
  const patronIds = Object.keys(patrons)
  const forgotten = patronIds.length <= MAX_PATRONS ? [] : patronIds
    .map((heroId, index) => ({ heroId, weight: patronWeight(patrons[heroId]), index }))
    .sort((left, right) => left.weight - right.weight || left.index - right.index)
    .slice(0, patronIds.length - MAX_PATRONS)
  for (const entry of forgotten) delete patrons[entry.heroId]
  // Кассы соперников: сначала нормализуются все, и только потом лишние
  // вытесняются — по последней игре, а не по порядку появления. Порядок
  // появления здесь ничего не значит: первым в карту попадает тот, с кем сыграли
  // первым, и он же может быть единственным, с кем играют весь вечер.
  const kept = new Map()
  for (const [npcId, gambler] of Object.entries(source.gamblers ?? {})) {
    const id = text(npcId, 120)
    if (!id) continue
    kept.set(id, {
      purse_cp: clamp(gambler?.purse_cp, 0, TAVERN_GAMBLER_PURSE_MAX_CP),
      // Когда с этим соседом играли в последний раз. Минуты кампании —
      // величина детерминированная и приезжает событием, поэтому replay
      // вытесняет ровно тех же.
      last_played_at_minutes: Math.max(0, integer(gambler?.last_played_at_minutes, 0)),
    })
  }
  const evicted = new Set(
    kept.size <= MAX_GAMBLERS ? [] : [...kept.entries()]
      // Ключ сортировки двойной: время последней игры, а при совпадении —
      // порядок в карте. Двух одинаковых ответов на «кого вытеснить» быть не
      // должно, иначе replay разойдётся со снимком.
      .map(([id, gambler], index) => ({ id, at: gambler.last_played_at_minutes, index }))
      .sort((left, right) => left.at - right.at || left.index - right.index)
      .slice(0, kept.size - MAX_GAMBLERS)
      .map((entry) => entry.id),
  )
  const gamblers = {}
  for (const [id, gambler] of kept) if (!evicted.has(id)) gamblers[id] = gambler
  return {
    schema_version: TAVERN_LIFE_SCHEMA_VERSION,
    patrons,
    gamblers,
  }
}

function patronFor(state = {}, heroId = '') {
  return safePatron(normalizeTavernState(state?.tavern).patrons[text(heroId, 120)])
}

/** Открытый раунд **этого** героя. Чужой раунд ему не мешает и не виден. */
export function tavernRoundFor(state = {}, heroId = '') {
  return patronFor(state, heroId).round
}

/**
 * Сколько сейчас в кошельке соперника. Пока он не проиграл и не выиграл ни
 * разу, это его вечерняя касса из сида; дальше — то, что записало событие.
 *
 * Счёт **переживает уход из зала**: кружки и скандалы обнуляются сменой сцены,
 * а деньги соседа — нет. Иначе выход за дверь и возврат обратно возвращали бы
 * ему полную кассу, и предел был бы только на бумаге.
 */
export function tavernGamblerPurseFor(state = {}, npcId = '') {
  const id = text(npcId, 120)
  const stored = normalizeTavernState(state?.tavern).gamblers[id]
  return stored ? stored.purse_cp : tavernGamblerFor(state, id).base_purse_cp
}

/**
 * Переезд денег в кассу соседа и обратно — единственным ответом на вопрос
 * «сколько на самом деле уехало».
 *
 * Нужна из-за потолка кассы. `TAVERN_GAMBLER_PURSE_MAX_CP` зажимает её сверху, и
 * на потолке очередная ставка в неё уже не влезает — а событие до ревью писало
 * `forfeited_cp: 200` и «сосед забрал ставку» при неподвижной кассе: двести
 * медяков молча уходили из мира, и сумма стола падала. Теперь остаток
 * называется своим именем: **доля заведения**. Хозяин зала за столом
 * присутствует всегда, и деньги, которые сосед унести уже не может, остаются
 * ему.
 *
 * `moved_cp` — сколько касса приняла (или отдала, если число отрицательное),
 * `house_cut_cp` — сколько от входящего платежа съел потолок. Оба уезжают в
 * payload: проверка «деньги за этим столом переезжают, а не исчезают» должна
 * читаться по событию, а не восстанавливаться вычитанием.
 *
 * @param {number} purseBeforeCp касса соседа до платежа
 * @param {number} amountCp сколько в неё кладут (отрицательное — сколько берут)
 */
export function tavernPurseTransfer(purseBeforeCp = 0, amountCp = 0) {
  const before = clamp(purseBeforeCp, 0, TAVERN_GAMBLER_PURSE_MAX_CP)
  const requested = integer(amountCp, 0)
  const after = Math.max(0, Math.min(TAVERN_GAMBLER_PURSE_MAX_CP, before + requested))
  const moved = after - before
  return Object.freeze({
    before_cp: before,
    after_cp: after,
    moved_cp: moved,
    house_cut_cp: Math.max(0, requested - moved),
  })
}

/**
 * Что переезд денег дописывает в событие. Пустой объект — касса не двигалась и
 * потолок ничего не съел: лишнее число в payload означало бы лишнюю запись в
 * карте касс на каждый закрытый раунд.
 */
export function tavernPurseTransferPayload(transfer) {
  if (!transfer || (transfer.moved_cp === 0 && transfer.house_cut_cp === 0)) return {}
  return {
    npc_purse_before_cp: transfer.before_cp,
    npc_purse_after_cp: transfer.after_cp,
    ...(transfer.house_cut_cp > 0 ? { house_cut_cp: transfer.house_cut_cp } : {}),
  }
}

/**
 * Все открытые раунды зала — по одному на героя.
 *
 * Порядок закреплён по идентификатору героя: события отмены пишутся из
 * исполнения команды (уход из сцены закрывает разом все столы), и двух разных
 * порядков в журнале быть не должно.
 */
export function tavernOpenRounds(state = {}) {
  const patrons = normalizeTavernState(state?.tavern).patrons
  return Object.keys(patrons).sort()
    .map((heroId) => patrons[heroId].round)
    .filter(Boolean)
}

/**
 * Все открытые раунды против этого соседа.
 *
 * Нужен ровно для одного: касса соперника общая, а раунд у каждого героя свой,
 * и по каждому открытому раунду сосед обязан быть в состоянии закрыть банк.
 * Сумма этих ставок и есть закреплённое покрытие.
 */
export function tavernOpenRoundsAgainst(state = {}, npcId = '') {
  const id = text(npcId, 120)
  if (!id) return []
  return tavernOpenRounds(state).filter((round) => round.npc_id === id)
}

/**
 * Сколько в кассе соседа закреплено за уже открытыми раундами.
 *
 * Стол на пятерых — норма формата, и касса у соседа при этом одна на всех. Без
 * закрепления пятеро героев открывали бы против кассы в 500 мм пять раундов по
 * 200: первые двое забирали банк, а третьему платить было уже нечем.
 */
export function tavernEarmarkedCpAgainst(state = {}, npcId = '') {
  return tavernOpenRoundsAgainst(state, npcId).reduce((total, round) => total + round.stake_cp, 0)
}

/**
 * Свободная касса соседа: чем он может ответить **сверх** уже открытых раундов.
 *
 * Это и есть второй инвариант стола. Открытие раунда, которого свободная касса
 * не покрывает, отклоняется (`TAVERN_OPPONENT_BROKE`), а закреплённое покрытие
 * не тратится ни на что другое — поэтому на момент ответа банк соседу закрыть
 * всегда есть чем. Ноль здесь означает «свободных денег нет»: играть с ним
 * дальше не о чем, но уже начатые раунды доигрываются.
 */
export function tavernFreePurseFor(state = {}, npcId = '') {
  return Math.max(0, tavernGamblerPurseFor(state, npcId) - tavernEarmarkedCpAgainst(state, npcId))
}

/**
 * Первый открытый раунд зала. Нужен ровно одному зрителю — тому, у кого своего
 * героя нет (ведущий, наблюдатель): у него карточка заведения не про его стол,
 * а про чужой, и показать ей нечего, кроме чужой кости. Порядок закреплён по
 * идентификатору героя, чтобы у двух открытых раундов был один и тот же ответ.
 */
function anyOpenRound(state = {}) {
  const patrons = normalizeTavernState(state?.tavern).patrons
  const heroId = Object.keys(patrons).filter((id) => patrons[id].round).sort()[0]
  return heroId ? patrons[heroId].round : null
}

/**
 * Самая крупная ставка, которую этот сосед может закрыть **сейчас**. Ноль — он
 * на мели, и садиться с ним не о чем. Уезжает игроку в карточке заведения:
 * отказ движка должен быть виден кнопкой, а не приходить ошибкой после клика.
 *
 * Считается по свободной кассе, а не по всей: покрытие открытых раундов уже
 * закреплено за ними, и обещать его второму герою кнопка не имеет права —
 * движок такую ставку не примет.
 */
export function tavernMaxStakeFor(state = {}, npcId = '') {
  const purse = tavernFreePurseFor(state, npcId)
  return TAVERN_STAKES_CP.filter((stake) => stake <= purse).at(-1) ?? 0
}

export function tavernDrinksFor(state = {}, heroId = '') {
  return patronFor(state, heroId).drinks
}

export function tavernScandalsFor(state = {}, heroId = '') {
  return patronFor(state, heroId).scandals
}

export function tavernEjected(state = {}, heroId = '') {
  return patronFor(state, heroId).ejected === true
}

