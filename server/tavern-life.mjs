/**
 * Жизнь таверны: кости на деньги и выпивка.
 *
 * Каталог ситуаций стола (`docs/dnd-table-situations.md`, E1 и E2) держал обе
 * строки в «нет», и обе — по одной причине: общий кубик на стол в проекте был
 * (`POST /api/rooms/:code/dice`, событие `PublicDieRolled`), а игры не было —
 * ни ставки, ни банка, ни проигранных денег. У выпивки не было даже источника:
 * единственный путь к истощению вёл через заклинание.
 *
 * Модуль детерминированный и без обращений к модели, как `captives.mjs`,
 * `parley.mjs` и `law-and-order.mjs`. Устроен он так:
 *
 * 1. **Соперник мечет первым, герой отвечает.** Раунд разложен на две команды
 *    не ради красоты: ручной бросок героя обязан идти против **объявленного**
 *    числа, а «перебить соперника» — это его бросок, и до него числа не
 *    существует. Поэтому `OpenTavernDiceRound` кидает публичный d20 соперника
 *    и закрепляет раунд в состоянии, а `AnswerTavernDiceRound` уже знает СЛ:
 *    она равна `npc_total + 1`. Карточка ручного броска не врёт ни разу.
 * 2. **Характер соперника — чистая функция сида кампании.** Честный он или
 *    шулер, насколько внимателен и насколько ловки его руки — всё выводится
 *    из `sessionCode` и идентификатора NPC, поэтому replay даёт того же
 *    человека. В состоянии этот флаг **не хранится**: то, чего нет в снимке,
 *    не может утечь игроку. И числа, которые игрок **видит**, от него тоже не
 *    зависят: СЛ обеих проверок стола выводится из внимательности и ловкости
 *    рук соседа и ни на единицу не сдвигается от того, шулер он или нет.
 * 3. **Шулер подменяет кость, а не прибавляет к сумме.** Если бы надбавка
 *    складывалась поверх выпавшего, стол видел бы «выпало 7, засчитано 12» и
 *    ловил бы шулера глазами, а не Проницательностью. Поэтому на стол
 *    кладётся уже подменённое число, а настоящая кость остаётся в броске с
 *    видимостью `gm_only`.
 * 4. **Кошелёк не уходит в минус, а банк не берётся из ниоткуда.** Ставка
 *    проверяется до первого события, банк переезжает целиком, и у соперника
 *    он не бесконечный: у каждого за столом свой кошелёк, который худеет от
 *    проигрышей и переживает уход из зала.
 * 5. **Раунд ключуется героем.** Стол на пятерых — норма формата, и один слот
 *    на всё заведение запирал бы кости для всех, пока один игрок не ответил
 *    (а если его уронили в 0 ОЗ — то и до конца сцены). Поэтому открытый
 *    раунд живёт в записи посетителя, а не в заведении.
 * 6. **Ставка уходит из кошелька в тот момент, когда кость легла на стол.**
 *    Это главный инвариант стола, и он не про бухгалтерию, а про риск.
 *
 *    Пока ставка лежала в кармане до расчёта, у героя оставался бесплатный
 *    выход из проигрышного раунда — и не один. Первый ревью поймало прямо:
 *    число соперника видно **до** решения, а «встать из-за стола» не стоило ни
 *    монеты, ни мировой минуты — цикл «выпало много, встал; выпало мало,
 *    ответил» приносил +600 мм при нулевых потерях. Заплату наложили запретом
 *    (уйти можно только из тупика), и второй ревью прошло сквозь неё за один
 *    ход: при ставке 200 и кошельке 200 кружка эля за 4 мм роняла кошелёк до
 *    196 — раунд становился «неотвечаемым по бедности», и герой вставал из-за
 *    стола даром, хотя соперник уже выбросил 19.
 *
 *    Запретами эта дыра не лечится, потому что дыра не в запрете: пока ставка
 *    в кармане, любой повод её оттуда убрать — это отмена уже сделанного
 *    выбора. Поэтому `OpenTavernDiceRound` **резервирует** ставку: она уходит
 *    из кошелька в банк раунда сразу, тем же событием, что кладёт кость на
 *    стол. Дальше она возвращается ровно тремя путями, и все три — расчёт:
 *    выигрыш (ставка и приз), ничья и разоблачение шулера (ставка). Проигрыш,
 *    поимка за руку и любой уход из раунда не возвращают ничего: уход — это
 *    сдача, и стоит он ровно столько же, сколько проигрыш.
 *
 *    Следствие важнее самой правки: «своих денег не хватает» перестаёт быть
 *    поводом тупика **по построению**. Ставка уже уплачена, и отвечать можно с
 *    пустым кошельком.
 * 7. **Касса соперника закрепляет покрытие открытых раундов.** Это второй
 *    инвариант стола, парный первому: ставка героя лежит на столе, а выплата по
 *    ней закреплена (earmark) в кассе соседа. Свободная касса — это касса минус
 *    сумма обязательств по всем открытым раундам (`tavernFreePurseFor`), и
 *    открыть раунд можно только под неё: не покрывает — отказ
 *    `TAVERN_OPPONENT_BROKE` на **открытии**. Закреплённое неприкосновенно:
 *    выигрыши других героев и любые списания идут из свободной кассы.
 *
 *    Инвариант держится сам, и это проверяется арифметикой, а не надеждой:
 *    открытие уменьшает свободную кассу ровно на ставку, а закрытие раунда
 *    освобождает закрепление и в тот же миг либо снимает ту же сумму (герой
 *    выиграл), либо кладёт её сверху (проигрыш, сдача). Свободная касса от этого
 *    не убывает никогда, значит на момент ответа соседу всегда есть чем закрыть
 *    банк — «соперник разорился, пока герой думал» невозможно **по построению**.
 *
 *    Так закрылся четвёртый заход одной и той же дыры. Пока покрытия не было,
 *    тупик существовал, и политика возвратов качалась между двумя лазейками:
 *    вернуть ставку из тупика — и сговор отряда становился прибылен («выпало
 *    плохо — товарищ грызёт кассу соседа, и ставка возвращается»; зонд ревью:
 *    62 возврата заведомо проигранной ставки на сотню попыток); не вернуть — и
 *    ставку терял невиновный, которому тупик устроили чужие руки. Выбирать между
 *    лазейками больше не из чего: тупика нет, а исходов у раунда два — доиграть
 *    (банк по результату) или сдаться (ставка сопернику).
 * 8. **Деньги стола не рождаются и не пропадают молча.** Касса соседа зажата
 *    потолком (`TAVERN_GAMBLER_PURSE_MAX_CP`), и на потолке ставка сдавшегося в
 *    неё уже не влезает. Раньше в этом месте она исчезала: событие несло
 *    «соперник забрал ставку», а касса не двигалась и полей о ней в payload не
 *    было. Теперь остаток называется своим именем — доля заведения
 *    (`house_cut_cp`, `tavernPurseTransfer`): деньги уходят не в никуда, а
 *    хозяину зала, и событие говорит об этом числом.
 *
 * Осознанные границы (решено, а не забыто):
 * - **своего реестра бросков здесь нет**: ручной кубик героя идёт тем же
 *   двухфазным путём (`server/roll-registry.mjs`), что у парлея и побега от
 *   стражи;
 * - **шулерство закон не судит.** Поступок в летописи (`world-deeds.mjs`) он
 *   заводит и молву рождает, но в таблицу преступлений (`law-and-order.mjs`)
 *   не входит: за руку ловит хозяин заведения, а не стража;
 * - **опьянение — существующее состояние `poisoned`**, а не своё. Помеха на
 *   проверки нужна была вся, и заводить рядом второе состояние с тем же
 *   смыслом значило бы развести числа по двум таблицам;
 * - **счёт кружек и скандалов живёт в сцене.** Ушли из таверны — счёт обнулён;
 *   похмелье при этом остаётся, потому что оно состояние героя, а не заведения.
 *   Вместе со счётом уходит и открытый раунд — но уходит он **событием**, а не
 *   молча: `AdvanceScene` пишет на каждый открытый раунд `TavernDiceRoundCancelled`
 *   со сдачей, и ставка со стола уезжает сопернику. Дверь — тот же уход от живой
 *   кости, и стоит он того же; молчаливое сжигание эскроу отличалось от сдачи
 *   ровно тем, что деньги пропадали из мира вместо того, чтобы переехать.
 */

