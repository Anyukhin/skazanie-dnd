/**
 * Поправки системного промпта под конкретную модель.
 *
 * Замер 2026-07-31 (`docs/model-benchmark-2026-07-31.md`) показал, что
 * `openai/gpt-5.6-luna` дешевле GLM-5.2 в 8,6 раза, но проваливает две метрики
 * стола: реплики NPC сжимаются до одного факта (голоса неразличимы), а факты
 * прошлых сцен теряются. Оба провала — про краткость, а не про способность:
 * маркеры речи модель сохраняет всегда.
 *
 * Здесь лежат измеренные компенсации промптом. Luna получает общую добавку
 * формы, а GLM-5.3-Flash — отдельный контракт только для Рассказчика: он не
 * протекает в социальный контроллер, где GLM и без него различает голоса.
 * Для незнакомых моделей добавка остаётся пустой.
 */

const LUNA_ADDENDUM = `
ДОПОЛНИТЕЛЬНЫЕ ТРЕБОВАНИЯ К ФОРМЕ ОТВЕТА (обязательные):
- Реплики и описания пиши развёрнуто: 2–4 полных предложения, не меньше 220
  символов. Однострочный ответ — ошибка, даже если факт передан верно.
- Говорящий обязан звучать как живой человек со своим словарём: используй его
  speech_profile целиком — темп, лексикон и манеру, а не только вводное слово.
  Добавь деталь от себя в его характере: присказку, отступление, оценку.
- Не сводись к голому факту. Факт оберни в наблюдение, воспоминание или
  отношение персонажа к происходящему.
- Прежде чем отвечать, найди в переданных данных факты прошлых сцен (обещания,
  прошлые разговоры, памятные детали) и вплети хотя бы один в текст дословно
  узнаваемым образом.`

const GLM_NARRATOR_ADDENDUM = `
ДОПОЛНИТЕЛЬНЫЙ КОНТРАКТ GLM ДЛЯ РАССКАЗЧИКА (обязательный, имеет высший
приоритет внутри требований к форме ответа):
- Повествуй только о результате, уже записанном в visible_events или
  visible_state_changes. Не описывай процесс, которым герой получил результат.
- Не ставь имя героя или местоимения «он/она» подлежащим нового действия.
  Запрещены даже безобидные действия и восприятие: подошёл, поднял, посмотрел,
  присел, сравнил, понял, вспомнил, решил, сказал, почувствовал и их синонимы.
- Для обычной проверки вообще не упоминай героя по имени и не заменяй действие
  метафорой вроде «вопрос распутывается» или «мысль складывается». Разрешён
  только безличный подтверждённый итог: «совпадение подтверждено», «след не
  удалось разобрать», «довод принят».
- При пустом permitted_npc_reactions ни NPC, ни люди, ни стража, ни толпа не
  совершают текущих действий, жестов и реплик. mood — статическая атмосфера,
  а не разрешение развивать её новым событием.
- open_promises и recent_interactions — только память. Обещание остаётся
  открытым: нельзя помещать обещанный предмет в сцену или объявлять обещание
  исполненным, нарушенным либо готовым к получению.
- sensory_anchors можно использовать дословно как статическое ощущение. Не
  объясняй их выдуманной кузней, факелом, существом, причиной или действием.
- Если в story_context есть memory_focus, обязательно вплети его cue почти
  дословно. summary/decision назови фактом прошлой сцены, interaction — прошлой
  репликой. Для promise используй только форму «Открытой нитью остаются слова
  [NPC] о [предмете и ориентире]»; не говори, что предмет лежит, оставлен,
  спрятан, ждёт, найден или находится у ориентира. Это память, а не текущее
  действие или состояние предмета.
- При memory_focus.kind=promise ответ состоит только из одного предложения со
  статической атмосферой и одного предложения об открытых словах NPC. Не
  называй проверку, успех, сообразительность, соображение, довод или
  «сопоставление сведений»: brief не сообщает нового знания об обещании.
- Используй ровно один memory_focus и игнорируй остальные open_promises,
  recent_interactions, recent_summaries и recent_decisions этого ответа. Если
  memory_focus.kind не равен promise, вообще не упоминай обещания и их предметы.
- При неудачной проверке используй memory_focus только тогда, когда его cue явно
  называет текущее место, предмет или цель сцены. Иначе ограничься подтверждённой
  неудачей и не притягивай прошлую улику.
- Не сравнивай разные типы улик и не объявляй между ними связь: колея не бывает
  похожа на нить, запах — на запись, обещание — на след. Размещай две памяти
  рядом только без причинного вывода, если связь не подтверждена событием.
- Не добавляй ни одного предмета, источника света, звука, запаха или персонажа,
  которого нет в narration_brief, memory_focus либо sensory_anchors.
- Обычный исход — ровно 1–2 предложения. Сначала назови статическую деталь
  сцены, затем безлично сформулируй только подтверждённый результат и предел
  знания. Третье предложение считается ошибкой. Не добавляй абзацы, варианты
  действий и продолжение сцены.
- Перед отправкой молча проверь грамматику, число предложений и каждый факт.
  Удали красивую фразу целиком, если для неё нет прямого поля в данных.

Разрешённая форма: «На обломке виден тот же узор, что и в памяти о прошлой
сцене; подтверждено только совпадение, а его причина пока неизвестна».
Для promise разрешено: «Открытой нитью остаются слова хозяйки о карте и медной
кружке; к этим словам не добавлено новых сведений».
Для неудачной проверки разрешено: «В золе видны свежие колеи. Их направление
определить не удалось; новых сведений результат не даёт».
Запрещённая форма: «Герой поднял обломок, сравнил узор и понял, кто его
оставил». Если для живой фразы нужен новый глагол героя или NPC, убери эту
фразу, а не выдумывай действие.

ФИНАЛЬНАЯ ПРОВЕРКА ПЕРЕД ОТПРАВКОЙ:
1. Не больше двух предложений.
2. При success=true и наличии memory_focus ответ обязан назвать его label и не
   меньше двух смысловых существительных из cue.
3. При memory_focus.kind=promise обязательна фраза «Открытой нитью остаются
   слова [NPC] о ...» и больше никакого вывода; не заменяй её общей
   «сообразительностью» или «сведениями».
4. Ни имя героя, ни его качество («сообразительность», «внимательность»,
   «ловкость») не совершают действие.
5. При success=false нет памяти, не связанной прямо с текущей сценой.
Нарушен любой пункт — перепиши ответ молча до отправки.`

const MODEL_ADDENDA = new Map([
  ['openai/gpt-5.6-luna', LUNA_ADDENDUM],
  ['openai/gpt-5.6-luna-pro', LUNA_ADDENDUM],
])

/**
 * @param {string | null | undefined} modelId
 * @returns {string} добавка к системному промпту или пустая строка
 */
export function styleAddendumFor(modelId) {
  return MODEL_ADDENDA.get(String(modelId ?? '')) ?? ''
}

/**
 * @param {string} basePrompt
 * @param {{ model?: string } | null | undefined} llmClient
 * @returns {string}
 */
export function promptForModel(basePrompt, llmClient) {
  const addendum = styleAddendumFor(llmClient?.model)
  return addendum ? `${basePrompt}\n${addendum}` : basePrompt
}

/**
 * Ролевой слой не должен протекать между агентами: ограничения Рассказчика
 * сделали бы живой ответ NPC формально неправильным.
 *
 * @param {string} basePrompt
 * @param {{ model?: string } | null | undefined} llmClient
 * @param {'narrator' | 'shared'} [role]
 * @returns {string}
 */
export function promptForModelRole(basePrompt, llmClient, role = 'shared') {
  const shared = promptForModel(basePrompt, llmClient)
  if (role === 'narrator' && String(llmClient?.model ?? '') === 'z-ai/glm-5.3-flash') {
    return `${shared}\n${GLM_NARRATOR_ADDENDUM}`
  }
  return shared
}

/**
 * Горячий путь хода работает без «размышлений» там, где провайдер разрешает
 * их выключить. У Luna замер 2026-07-31 показал, что с добавкой формы reasoning
 * не даёт качества, а хвост задержки без него исчезает. RouterAI требует
 * reasoning у GLM-5.3-Flash, поэтому для неё задан минимальный поддерживаемый
 * effort `low`. Незнакомая модель остаётся на умолчании провайдера.
 *
 * @param {string | null | undefined} modelId
 * @returns {{ enabled: false } | { effort: 'low' } | null}
 */
export function reasoningProfileFor(modelId) {
  if (String(modelId ?? '') === 'z-ai/glm-5.3-flash') return { effort: 'low' }
  const known = new Set([
    'z-ai/glm-5.2',
    'deepseek/deepseek-v4-flash',
    'openai/gpt-5.6-luna',
    'openai/gpt-5.6-luna-pro',
  ])
  return known.has(String(modelId ?? '')) ? { enabled: false } : null
}
