/**
 * Множитель тайм-аутов для общего раннера.
 *
 * HTTP-тесты поднимают настоящий сервер и на машине разработчика укладываются с
 * запасом: `hit-dice-api` — 11 с при лимите 60. На общем раннере GitHub, где
 * рядом идут другие job'ы, тот же тест вышел за 60 с — при зелёном локальном
 * прогоне той же ревизии и на пути, которого правка вообще не касалась.
 *
 * Поэтому лимит зависит от среды: локально он прежний и ловит зависание, на
 * раннере втрое больше, потому что там мерил бы загруженность чужими job'ами,
 * а не поведение кода. Тот же приём уже применён к wall-clock бюджетам
 * (`tactical-map-budget`) и к длинному MVP-сценарию.
 */
const SHARED_RUNNER = process.env.CI === 'true' || process.env.GITHUB_ACTIONS === 'true'

/**
 * @param {number} localMs строгий лимит для машины разработчика
 * @returns {number}
 */
export function runnerTimeout(localMs) {
  return SHARED_RUNNER ? localMs * 3 : localMs
}
